from typing import Optional

import pyrogram
from pyrogram import raw, types, utils


class ExportTonWalletSecretPhrase:
    async def export_ton_wallet_secret_phrase(
        self: "pyrogram.Client",
        password: Optional[str] = None
    ) -> "types.TonWalletSecretPhraseParts":
        """Start the export of the secret phrase of the TON wallet of the current user.

        Works only if :obj:`~pyrogram.types.TonWalletState` *can_export_phrase* is True.
        The secret phrase is stored in encrypted parts on several data centers: the returned token allows to fetch
        each part with :meth:`~pyrogram.Client.get_ton_wallet_encrypted_secret_phrase_part`.

        .. warning::

            The secret phrase gives full control over the funds of the wallet: never share it, nor the token and the
            parts returned by these methods. Pyrofork doesn't implement the decryption of the parts. TDLib
            (``getTonWalletSecretPhrase``) fetches the part of each data center returned by
            :meth:`~pyrogram.Client.get_ton_wallet_backup_holder_dcs` for a new temporary key pair, decrypts the
            parts and XORs them to get the secret phrase as space separated words.

        .. include:: /_includes/usable-by/users.rst

        Parameters:
            password (``str``, *optional*):
                The 2-step verification password of the current user.
                As TDLib documents, omit it unless the request without a password fails with ``PASSWORD_MISSING``.

        Returns:
            :obj:`~pyrogram.types.TonWalletSecretPhraseParts`: On success, the token to fetch the parts is returned.

        Example:
            .. code-block:: python

                parts = await app.export_ton_wallet_secret_phrase("password")

                for dc in await app.get_ton_wallet_backup_holder_dcs():
                    # public_key belongs to a temporary key pair generated by your own code
                    data = await app.get_ton_wallet_encrypted_secret_phrase_part(parts.token, public_key, dc.dc_id)
        """
        r = await self.invoke(
            raw.functions.wallet.ExportSecretPhrase(
                password=utils.compute_password_check(
                    await self.invoke(raw.functions.account.GetPassword()), password
                ) if password else None
            )
        )

        return types.TonWalletSecretPhraseParts._parse(self, r)
