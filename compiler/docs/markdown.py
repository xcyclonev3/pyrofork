"""Generate browseable GitHub Markdown API references from the source tree."""
from __future__ import annotations

import argparse
import ast
import csv
import os
import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DOCS = ROOT / "docs"
PACKAGE = ROOT / "pyrogram"
MARKER = "<!-- Generated by compiler/docs/markdown.py; do not edit. -->"
TICK = chr(96)
FENCE = TICK * 3
SYMBOL_PATHS: dict[str, tuple[Path, str | None]] = {}
REFERENCE_DEFS: dict[str, str] = {}
ROLE_PATTERN = re.compile(r":(?:py:)?(obj|class|meth|func|attr|exc|mod):\x60([^\x60]+)\x60")


def code(value: str) -> str:
    return f"{TICK}{value}{TICK}"


def relative_link(source: Path, target: Path, anchor: str | None = None) -> str:
    value = Path(os.path.relpath(target, source.parent)).as_posix()
    return value + (f"#{anchor}" if anchor else "")


def source_files(directory: Path):
    return sorted(path for path in directory.rglob("*.py")
                  if path.name != "__init__.py" and "__pycache__" not in path.parts)


def module_nodes(path: Path):
    source = path.read_text(encoding="utf-8")
    return ast.parse(source), source


def top_level_classes(tree: ast.Module):
    return [node for node in tree.body if isinstance(node, ast.ClassDef) and not node.name.startswith("_")]


def public_functions(node: ast.ClassDef):
    return [child for child in node.body
            if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef)) and not child.name.startswith("_")]


def signature(node: ast.FunctionDef | ast.AsyncFunctionDef, name: str | None = None) -> str:
    args = node.args
    positional = list(args.posonlyargs) + list(args.args)
    if positional and positional[0].arg in {"self", "cls"}:
        positional = positional[1:]
    defaults = [None] * (len(positional) - len(args.defaults)) + list(args.defaults)
    parts = []
    for index, (arg, default) in enumerate(zip(positional, defaults)):
        item = arg.arg
        if arg.annotation:
            item += f": {ast.unparse(arg.annotation)}"
        if default is not None:
            item += f" = {ast.unparse(default)}"
        parts.append(item)
        if args.posonlyargs and index == len(args.posonlyargs) - 1:
            parts.append("/")
    if args.vararg:
        item = "*" + args.vararg.arg
        if args.vararg.annotation:
            item += f": {ast.unparse(args.vararg.annotation)}"
        parts.append(item)
    elif args.kwonlyargs:
        parts.append("*")
    for arg, default in zip(args.kwonlyargs, args.kw_defaults):
        item = arg.arg
        if arg.annotation:
            item += f": {ast.unparse(arg.annotation)}"
        if default is not None:
            item += f" = {ast.unparse(default)}"
        parts.append(item)
    if args.kwarg:
        item = "**" + args.kwarg.arg
        if args.kwarg.annotation:
            item += f": {ast.unparse(args.kwarg.annotation)}"
        parts.append(item)
    function_name = name or node.name
    prefix = "async def" if isinstance(node, ast.AsyncFunctionDef) else "def"
    result = f" -> {ast.unparse(node.returns)}" if node.returns else ""
    if len(parts) <= 2 and sum(map(len, parts)) < 92:
        return f"{prefix} {function_name}({', '.join(parts)}){result}: ..."
    return f"{prefix} {function_name}(\n" + ",\n".join(f"    {part}" for part in parts) + f"\n){result}: ..."


def role_parts(value: str):
    if "<" in value and value.endswith(">"):
        label, target = value.rsplit("<", 1)
        return label.strip().lstrip("~"), target[:-1].strip().lstrip("~")
    value = value.strip()
    return value.split(".")[-1].lstrip("~"), value.lstrip("~")


def inline_markup(line: str, output_path: Path, source_path: Path | None = None) -> str:
    line = re.sub(
        r":doc:\x60([^\x60]+)\x60",
        lambda match: convert_doc_role(match, source_path, output_path)
        if source_path else code(match.group(1).split("<", 1)[0].strip()),
        line,
    )

    def replace_role(match):
        label, target = role_parts(match.group(2))
        resolved = SYMBOL_PATHS.get(target)
        if not resolved:
            return code(label)
        target_path, target_anchor = resolved
        return f"[{code(label)}]({relative_link(output_path, target_path, target_anchor)})"

    line = ROLE_PATTERN.sub(replace_role, line)
    custom_roles = {
        "strike": lambda value: "~~" + value + "~~",
        "strike-italic": lambda value: "~~*" + value + "*~~",
        "bold-underline": lambda value: "**" + value + "**",
        "underline": lambda value: value,
        "emoji": lambda value: value,
        "guilabel": lambda value: code(value),
    }
    line = re.sub(
        r":(strike|strike-italic|bold-underline|underline|emoji|guilabel):\x60([^\x60]+)\x60",
        lambda match: custom_roles[match.group(1)](match.group(2)),
        line,
    )
    line = re.sub(
        r"\x60([^\x60]+)\x60_(?![\w\x60])",
        lambda match: f"[{match.group(1)}]({REFERENCE_DEFS.get(match.group(1), '')})"
        if REFERENCE_DEFS.get(match.group(1)) else code(match.group(1)),
        line,
    )
    line = re.sub(
        r"\x60([^<\x60]+?)\s+<([^>\x60]+)>\x60_?",
        lambda match: convert_reference_link(match, source_path, output_path)
        if source_path else f"[{match.group(1).strip()}]({match.group(2).strip()})",
        line,
    )
    line = re.sub(r"\x60\x60([^\x60]+)\x60\x60", lambda match: code(match.group(1)), line)
    for name, url in REFERENCE_DEFS.items():
        line = re.sub(rf"(?<![\w\x60]){re.escape(name)}_(?![\w\x60])",
                      f"[{name}]({url})", line)
    return line


def convert_reference_link(match: re.Match, source_path: Path, output_path: Path):
    label, target = match.group(1).strip(), match.group(2).strip()
    if target.startswith(("https://", "http://", "mailto:", "tg://")):
        return f"[{label}]({target})"
    if target.lower() in {"handlers", "filters", "decorators"}:
        mapped = DOCS / "api" / target.lower() / "README.md"
        return f"[{label}]({relative_link(output_path, mapped)})"
    mapped = map_old_doc(source_path, target)
    if mapped:
        return f"[{label}]({relative_link(output_path, mapped)})"
    return f"[{label}]({target})"


def take_indented(lines: list[str], start: int, base_indent: int):
    body = []
    index = start
    while index < len(lines):
        current = lines[index]
        if not current.strip():
            body.append("")
            index += 1
            continue
        indent = len(current) - len(current.lstrip())
        if indent <= base_indent:
            break
        body.append(current)
        index += 1
    while body and not body[0].strip():
        body.pop(0)
    while body and not body[-1].strip():
        body.pop()
    return body, index


def dedent_block(lines: list[str]):
    width = min((len(line) - len(line.lstrip()) for line in lines if line.strip()), default=0)
    return [line[width:] if line.strip() else "" for line in lines]


def map_old_doc(source_path: Path, target: str):
    raw_target = target.strip()
    fragment = raw_target.split("#", 1)[1] if "#" in raw_target else ""
    target = raw_target.split("#", 1)[0]
    if not target or "://" in target:
        return None
    if target.startswith("/") and target.lstrip("/").startswith("faq") and fragment:
        return DOCS / "faq" / f"{fragment}.md"
    source_root = (DOCS / "source").resolve()
    candidate = (source_path.parent / target).resolve()
    try:
        parts = list(candidate.relative_to(source_root).parts)
    except ValueError:
        parts = list(Path(target.lstrip("/")).parts)
        # API docstrings often use paths relative to the original Python source
        # tree. Keep the meaningful documentation subtree after ../ segments.
        for root_name in ("topics", "start", "intro", "faq", "examples", "api", "telegram"):
            if root_name in parts:
                parts = parts[parts.index(root_name):]
                break
    if parts and parts[0] == "faq" and fragment:
        return DOCS / "faq" / f"{fragment}.md"
    if not parts:
        return DOCS / "README.md"
    if parts[-1].endswith(".rst"):
        parts[-1] = Path(parts[-1]).stem
    remap = {"intro": "getting-started", "start": "getting-started", "topics": "guides"}
    if parts[:2] == ["start", "examples"]:
        parts = ["examples", *parts[2:]]
    else:
        parts[0] = remap.get(parts[0], parts[0])
    if parts[0] == "getting-started" and len(parts) > 1:
        parts[1] = {
            "install": "installation",
            "quickstart": "quick-start",
            "auth": "authorization",
            "invoking": "calling-methods",
            "errors": "error-handling",
        }.get(parts[1], parts[1])
    if parts[:2] == ["api", "errors"] and len(parts) > 2:
        error_codes = {
            "see-other": "303", "bad-request": "400", "unauthorized": "401",
            "forbidden": "403", "not-acceptable": "406", "flood": "420",
            "internal-server-error": "500", "not-found": "404",
        }
        if parts[2] != "index":
            parts[2] = error_codes.get(parts[2], parts[2])
    if parts[:2] == ["telegram", "functions"]:
        parts = ["api", "raw", "functions", *parts[2:]]
    elif parts[:2] == ["telegram", "types"]:
        parts = ["api", "raw", "types", *parts[2:]]
    elif parts[:2] == ["telegram", "base"]:
        parts = ["api", "raw", "base", *parts[2:]]
    if parts[:2] == ["api", "handlers"] or parts[:2] == ["api", "decorators"] or parts[:2] == ["api", "filters"]:
        parts = [*parts[:2], "README"]
    if parts[-1] == "index":
        parts[-1] = "README"
    return DOCS.joinpath(*parts).with_suffix(".md")


def convert_doc_role(match: re.Match, source_path: Path, output_path: Path):
    value = match.group(1).strip()
    if "<" in value and value.endswith(">"):
        label, target = value.rsplit("<", 1)
        label, target = label.strip(), target[:-1].strip()
    else:
        target = value
        label = Path(target.split("#", 1)[0]).name.replace("-", " ").title()
    symbol = SYMBOL_PATHS.get(target) or SYMBOL_PATHS.get(target.lstrip("~"))
    if symbol:
        target_path, target_anchor = symbol
        return f"[{label}]({relative_link(output_path, target_path, target_anchor)})"
    if target.lower() in {"handlers", "filters", "decorators"}:
        target_path = DOCS / "api" / target.lower() / "README.md"
        return f"[{label}]({relative_link(output_path, target_path)})"
    target_path = map_old_doc(source_path, target)
    if target_path:
        return f"[{label}]({relative_link(output_path, target_path)})"
    return label


def rst_to_markdown(text: str, source_path: Path, output_path: Path) -> str:
    role_pattern = re.compile(r":((?:py:)?(?:obj|class|meth|func|attr|exc|mod)):\x60([^\x60]*?)\x60", re.DOTALL)
    def normalize_role(match):
        value = re.sub(r"\s+", " ", match.group(2))
        return ":" + match.group(1) + ":" + TICK + value + TICK
    text = role_pattern.sub(normalize_role, text)
    lines = text.expandtabs(4).splitlines()
    output = []
    levels = {"=": 1, "-": 2, "^": 3, '"': 4, "~": 5, "+": 6, "#": 2, "*": 2}
    for match in re.finditer(r"(?m)^\s*\.\.\s+_([^:]+):\s*(\S.*)?$", text):
        name = match.group(1).strip(" " + TICK)
        target = (match.group(2) or "").strip()
        if target.startswith(("https://", "http://", "mailto:")):
            REFERENCE_DEFS[name] = target
        elif target:
            mapped = map_old_doc(source_path, target)
            REFERENCE_DEFS[name] = relative_link(output_path, mapped) if mapped else target
    index = 0
    while index < len(lines):
        line = lines[index]
        stripped = line.strip()
        definition = re.match(r"^\s*\.\.\s+_([^:]+):\s*(\S.*)?$", line)
        if definition:
            index += 1
            continue
        underline = re.fullmatch(r"\s*(=+|-+|\^+|\"+|~+|\++|#+|\*+)\s*", lines[index + 1]) if index + 1 < len(lines) else None
        if stripped and underline:
            marker = underline.group(1)[0]
            output.extend(["#" * levels.get(marker, 2) + " " + inline_markup(stripped, output_path, source_path), ""])
            index += 2
            continue
        section = re.match(r"^\s*(Parameters|Returns|Raises|Examples?|Attributes|Details|Notes):\s*$", line, re.I)
        if section:
            kind = section.group(1).lower()
            body, next_index = take_indented(lines, index + 1, len(line) - len(line.lstrip()))
            output.extend([f"## {kind.title()}", ""])
            section_lines = dedent_block(body)
            if kind == "parameters":
                field_indent = None
                for value in section_lines:
                    field = re.match(r"^([A-Za-z_][\w*]*)\s+\((.*?)\):\s*$", value.strip())
                    if field:
                        field_indent = len(value) - len(value.lstrip())
                        output.append(f"- **{code(field.group(1))}** ({inline_markup(field.group(2), output_path, source_path)})")
                    elif value.strip():
                        indent = len(value) - len(value.lstrip())
                        prefix = "  " if field_indent is not None and indent > field_indent else ""
                        output.append(prefix + inline_markup(value.strip(), output_path, source_path))
                    else:
                        output.append("")
            else:
                nested = rst_to_markdown("\n".join(section_lines), source_path, output_path).rstrip()
                output.extend(nested.splitlines())
            output.append("")
            index = next_index
            continue
        directive = re.match(r"^(\s*)\.\.\s+([a-zA-Z0-9_-]+)\s*:{1,2}(?:\s*(.*))?$", line)
        if directive:
            indent = len(directive.group(1))
            kind = directive.group(2).lower()
            argument = (directive.group(3) or "").strip()
            body, next_index = take_indented(lines, index + 1, indent)
            if kind in {"code-block", "sourcecode", "parsed-literal"}:
                language = argument if kind != "parsed-literal" else "text"
                output.extend([FENCE + language, *dedent_block(body), FENCE, ""])
            elif kind in {"note", "warning", "tip", "important", "admonition"}:
                title = argument if kind == "admonition" else kind.title()
                alert = title.upper() if title.lower() in {"note", "warning", "important", "tip", "caution"} else "NOTE"
                output.append(f"> [!{alert}]")
                if kind == "admonition" and title:
                    output.append(f"> **{inline_markup(title, output_path, source_path)}**")
                body = [value for value in body if not re.match(r"\s*:[a-zA-Z_-]+:", value)]
                nested = rst_to_markdown("\n".join(dedent_block(body)), source_path, output_path).rstrip()
                output.extend("> " + value if value else ">" for value in nested.splitlines())
                output.append("")
            elif kind in {"hlist"}:
                values = [value for value in dedent_block(body)
                          if value.strip() and not value.lstrip().startswith(":")]
                output.extend(inline_markup(value, output_path, source_path) for value in values)
                output.append("")
            elif kind in {"contents", "toctree", "currentmodule", "automodule", "autoclass",
                          "automethod", "autofunction", "autodecorator", "autosummary", "raw",
                          "role", "math", "rubric"}:
                pass
            elif kind == "csv-table":
                header, rows = None, []
                for value in body:
                    if value.lstrip().startswith(":header:"):
                        try:
                            header = next(csv.reader([value.split(":", 2)[-1].strip()]))
                        except csv.Error:
                            pass
                    elif value.strip() and not value.lstrip().startswith(":"):
                        try:
                            rows.append(next(csv.reader([value.strip()])))
                        except csv.Error:
                            pass
                if argument:
                    output.extend([f"### {inline_markup(argument, output_path, source_path)}", ""])
                if rows:
                    header = header or rows.pop(0)
                    output.extend(["| " + " | ".join(header) + " |",
                                   "| " + " | ".join("---" for _ in header) + " |"])
                    output.extend(
                        "| " + " | ".join(inline_markup(cell.strip(), output_path, source_path).replace("|", "\\|") for cell in row) + " |"
                        for row in rows
                    )
                    output.append("")
            elif kind in {"image", "figure"}:
                options = {}
                for value in body:
                    option = re.match(r"\s*:([a-zA-Z_-]+):\s*(.*)", value)
                    if option:
                        options[option.group(1)] = option.group(2)
                asset_path = (source_path.parent / argument.lstrip("/")).resolve()
                if asset_path.exists():
                    try:
                        asset_rel = asset_path.relative_to((DOCS / "source").resolve())
                        mapped = DOCS / asset_rel
                    except ValueError:
                        mapped = asset_path
                    output.append(f"![{options.get('alt', '')}]({relative_link(output_path, mapped)})")
                else:
                    if options.get("alt"):
                        output.append(options["alt"])
                output.append("")
            elif kind == "centered":
                output.extend([inline_markup(" ".join(value.strip() for value in body), output_path, source_path), ""])
            elif kind == "include":
                audience = {"users.rst": "User accounts", "bots.rst": "Bots",
                            "users-bots.rst": "User accounts and bots"}.get(argument.rsplit("/", 1)[-1])
                if audience:
                    output.extend([f"**Available to:** {audience}.", ""])
            elif kind not in {
                "contents", "toctree", "currentmodule", "automodule", "autoclass",
                "automethod", "autofunction", "autodecorator", "autosummary", "raw", "role",
                "math", "rubric",
            }:
                output.append(inline_markup(stripped, output_path, source_path))
            index = next_index
            continue
        line = re.sub(r":doc:\x60([^\x60]+)\x60",
                      lambda match: convert_doc_role(match, source_path, output_path), line)
        line = inline_markup(line, output_path, source_path)
        output.append(line.rstrip())
        index += 1
    while output and not output[-1].strip():
        output.pop()
    return "\n".join(output) + "\n"


def add_symbol(name: str, path: Path, target_anchor: str | None = None):
    SYMBOL_PATHS[name] = (path, target_anchor)


def slug(value: str):
    return re.sub(r"\s+", "-", re.sub(r"[^\w\- ]", "", value.lower().strip()))


def error_filename(name: str):
    value = re.sub(r"(?<!^)(?=[A-Z][a-z])", "-", name).lower()
    return value + ".md"


def page(title: str, body: str, source: str | None = None):
    body_lines = body.strip().splitlines()
    headings = []
    seen = defaultdict(int)
    in_fence = False
    for line in body_lines:
        if line.startswith(FENCE):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        match = re.match(r"^(#{2,3})\s+(.+?)\s*#*\s*$", line)
        if not match or match.group(2).strip().lower() == "contents":
            continue
        heading = match.group(2)
        base_anchor = slug(heading)
        count = seen[base_anchor]
        seen[base_anchor] += 1
        anchor = base_anchor if count == 0 else f"{base_anchor}-{count}"
        headings.append((len(match.group(1)), heading, anchor))
    if len(body_lines) >= 100 and len(headings) >= 5 and not any(
        re.match(r"^##\s+Contents\s*$", line, re.I) for line in body_lines
    ):
        contents = ["## Contents", ""]
        for level, heading, anchor in headings:
            contents.append("  " * (level - 2) + f"- [{heading}](#{anchor})")
        contents.append("")
        body_lines.insert(0, "## Contents")
        body_lines[1:1] = contents[1:]
        body = "\n".join(body_lines)
    footer = f"\n\n_Source: {code(source)}._" if source else ""
    return f"{MARKER}\n\n# {title}\n\n{body.strip()}{footer}\n"


def doc_body(node: ast.AST, output: Path):
    value = ast.get_docstring(node, clean=True)
    if not value:
        return "No docstring is defined in the source."
    result = rst_to_markdown(value, ROOT / "docs" / "source" / "api" / "_generated.rst", output).strip()
    adjusted = []
    in_fence = False
    for line in result.splitlines():
        if line.startswith(FENCE):
            in_fence = not in_fence
        if not in_fence:
            line = re.sub(r"^(#{1,5}) ", lambda match: "#" * min(len(match.group(1)) + 1, 6) + " ", line)
        adjusted.append(line)
    result = "\n".join(adjusted)
    return result or "No additional description is defined in the source."


def callable_page(title: str, node, output: Path, qualified: str, source: str):
    body = (f"**Qualified name:** {code(qualified)}\n\n"
            f"## Signature\n\n{FENCE}python\n{signature(node)}\n{FENCE}\n\n"
            f"## Documentation\n\n{doc_body(node, output)}")
    return page(title, body, source)


def class_page(title: str, node: ast.ClassDef, output: Path, qualified: str, source: str):
    init = next((item for item in node.body
                 if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)) and item.name == "__init__"), None)
    body = f"**Qualified name:** {code(qualified)}\n\n"
    if init:
        body += f"## Constructor\n\n{FENCE}python\n{signature(init, '__init__')}\n{FENCE}\n\n"
    body += f"## Documentation\n\n{doc_body(node, output)}"
    return page(title, body, source)


def exception_page(title: str, node: ast.ClassDef, output: Path, qualified: str, source: str):
    init = next((item for item in node.body
                 if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)) and item.name == "__init__"), None)
    if init is None and qualified.startswith("pyrogram.errors."):
        error_tree, _ = module_nodes(PACKAGE / "errors" / "rpc_error.py")
        rpc_error = next((item for item in top_level_classes(error_tree) if item.name == "RPCError"), None)
        if rpc_error:
            init = next((item for item in rpc_error.body
                         if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)) and item.name == "__init__"), None)
    body = f"**Qualified name:** {code(qualified)}\n\n"
    fields = []
    for child in node.body:
        if isinstance(child, ast.Assign) and isinstance(child.value, ast.Constant):
            for target in child.targets:
                if isinstance(target, ast.Name) and target.id in {"CODE", "ID", "NAME", "MESSAGE"}:
                    fields.append((target.id, repr(child.value.value)))
    if fields:
        body += "## Error metadata\n\n| Field | Value |\n| --- | --- |\n"
        body += "\n".join(f"| {code(name)} | {code(value)} |" for name, value in fields) + "\n\n"
    if init:
        body += f"## Constructor\n\n{FENCE}python\n{signature(init, '__init__')}\n{FENCE}\n\n"
    body += f"## Documentation\n\n{doc_body(node, output)}"
    return page(title, body, source)


def put(pages: dict[Path, str], path: Path, content: str):
    relative = path.relative_to(DOCS)
    previous = pages.get(relative)
    if previous is not None and previous != content:
        raise ValueError(f"Two public API objects map to the same documentation page: {relative}")
    pages[relative] = content


def find_public_sources():
    methods, types, enums, handlers, decorators, bound, filters, filter_classes, errors = [], [], [], [], [], [], [], [], []
    for path in source_files(PACKAGE / "methods"):
        tree, _ = module_nodes(path)
        rel = path.relative_to(PACKAGE / "methods")
        for cls in top_level_classes(tree):
            for node in public_functions(cls):
                (decorators if rel.parts and rel.parts[0] == "decorators" else methods).append((rel, cls, node))
    for path in source_files(PACKAGE / "types"):
        tree, _ = module_nodes(path)
        rel = path.relative_to(PACKAGE / "types")
        module = ".".join(rel.parent.parts)
        for cls in top_level_classes(tree):
            types.append((rel, module, cls))
            for node in public_functions(cls):
                if node.name not in {"__init__", "__str__", "__repr__", "__eq__", "__setstate__", "__getstate__", "bind"}:
                    bound.append((rel, cls, node))
    for path in source_files(PACKAGE / "enums"):
        tree, _ = module_nodes(path)
        enums.extend((path.relative_to(PACKAGE / "enums"), cls) for cls in top_level_classes(tree))
    for path in source_files(PACKAGE / "handlers"):
        tree, _ = module_nodes(path)
        handlers.extend((path.relative_to(PACKAGE / "handlers"), cls) for cls in top_level_classes(tree))
    filter_tree, _ = module_nodes(PACKAGE / "filters.py")
    filter_functions = {node.name: node for node in filter_tree.body
                        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and not node.name.startswith("_")}
    filter_classes.extend((node.name, node) for node in top_level_classes(filter_tree))
    filters.extend((name, node, None) for name, node in filter_functions.items() if not name.endswith("_filter"))
    for node in filter_tree.body:
        if isinstance(node, ast.Assign) and isinstance(node.value, ast.Call):
            factory = node.value.func.id if isinstance(node.value.func, ast.Name) else ""
            if factory == "create":
                for target in node.targets:
                    if isinstance(target, ast.Name) and not target.id.startswith("_"):
                        filters.append((target.id, filter_functions.get(f"{target.id}_filter"), "builtin"))
    for error_source in (PACKAGE / "errors" / "__init__.py", PACKAGE / "errors" / "rpc_error.py"):
        if error_source.exists():
            tree, _ = module_nodes(error_source)
            errors.extend((error_source.relative_to(PACKAGE / "errors"), cls) for cls in top_level_classes(tree))
    exception_root = PACKAGE / "errors" / "exceptions"
    if exception_root.exists():
        for path in source_files(exception_root):
            tree, _ = module_nodes(path)
            errors.extend((path.relative_to(PACKAGE / "errors"), cls) for cls in top_level_classes(tree))
    # Generated RPC files can contain a repeated class name when Telegram has
    # reused an error identifier. Python exposes the last definition in a module.
    effective_errors = {}
    for rel, cls in errors:
        effective_errors[(rel, cls.name)] = (rel, cls)
    errors = list(effective_errors.values())
    return methods, types, enums, handlers, decorators, bound, filters, filter_classes, errors


